def build_launch_prompt(request_id, task_url):
    # Stable per REQ: rebuilding never silently selects a different visible text.
    index = int.from_bytes(hashlib.sha256(request_id.encode("utf-8")).digest()[:8], "big") % len(LAUNCH_PHRASES)
    return LAUNCH_PHRASES[index] + "\n" + task_url


def is_launch_prompt(prompt, request_id):
    lines = prompt.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if len(lines) != 2 or lines[0] not in LAUNCH_PHRASES:
        return False
    url = urlparse(lines[1])
    return (url.scheme in {"http", "https"} and bool(url.netloc)
            and unquote(url.path.rstrip("/").rsplit("/", 1)[-1]) == request_id + ".md")
